-- MVC TEST (CLASSICDEV only), part 2: test copies for face-recognition, face-consent and device-check, and override rows
-- for the XYZADMIN test client (run 03 and 04 first). import-eye is tested against the real CLASSICNEW.IMPORT_EYE (rows deleted afterwards).
-- Removed by 05_mvc_test_cleanup.sql (drops every TMVC_* table and the 'MVC TEST override' rows).
ALTER SESSION SET CURRENT_SCHEMA = CLASSICNEW;

DECLARE
  cid NUMBER;
  n   NUMBER;
BEGIN
  SELECT CTRL_ID INTO cid FROM MOBILE_CONTROL WHERE UPPER(USER_ID) = 'XYZADMIN';

  -- face tables: copies with LOCA / UNIT columns (as in the MVC design)
  FOR t IN (SELECT column_value tn FROM TABLE(sys.odcivarchar2list('M_EMPL_FACERECOGNITION', 'M_EMPL_FACE_CONSENT'))) LOOP
    SELECT COUNT(*) INTO n FROM user_tables WHERE table_name = 'TMVC_' || t.tn;
    IF n = 0 THEN
      EXECUTE IMMEDIATE 'CREATE TABLE CLASSICNEW.TMVC_' || t.tn || ' AS SELECT * FROM PAY_BATE_NOR2027.' || t.tn;
      EXECUTE IMMEDIATE 'ALTER TABLE CLASSICNEW.TMVC_' || t.tn || ' ADD (LOCA VARCHAR2(10), UNIT VARCHAR2(20))';
      EXECUTE IMMEDIATE 'UPDATE CLASSICNEW.TMVC_' || t.tn || q'[ SET LOCA = 'ATE', UNIT = 'ANANDA']';
    END IF;
  END LOOP;

  -- a user table with registered devices: DEVUSER1 has one phone, DEVUSER2 has two
  SELECT COUNT(*) INTO n FROM user_tables WHERE table_name = 'TMVC_USER_JAG';
  IF n = 0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE CLASSICNEW.TMVC_USER_JAG (USER_ORA VARCHAR2(30), PHONE_ID VARCHAR2(60))';
    EXECUTE IMMEDIATE q'[INSERT INTO CLASSICNEW.TMVC_USER_JAG VALUES ('DEVUSER1', 'PH-1')]';
    EXECUTE IMMEDIATE q'[INSERT INTO CLASSICNEW.TMVC_USER_JAG VALUES ('DEVUSER2', 'PH-1')]';
    EXECUTE IMMEDIATE q'[INSERT INTO CLASSICNEW.TMVC_USER_JAG VALUES ('DEVUSER2', 'PH-2')]';
    EXECUTE IMMEDIATE q'[INSERT INTO CLASSICNEW.TMVC_USER_JAG VALUES ('NODEVICE', NULL)]';
  END IF;

  FOR d IN (SELECT * FROM MOBILE_MASTER_CONFIG
             WHERE CTRL_ID IS NULL AND APP_MODE = 'MVC' AND ITEM_KEY IN ('face-recognition', 'face-consent', 'device-check')) LOOP
    SELECT COUNT(*) INTO n FROM MOBILE_MASTER_CONFIG WHERE CTRL_ID = cid AND APP_MODE = 'MVC' AND ITEM_KEY = d.ITEM_KEY;
    IF n = 0 THEN
      INSERT INTO MOBILE_MASTER_CONFIG (CFG_ID, CTRL_ID, APP_MODE, SEQ_NO, ITEM_KEY, DESCRIPTION, OP_TYPE, SCHEMA_SOURCE, TABLE_NAME, COLUMN_LIST, ALIASES,
             FILTER_COLUMN, FILTER_VALUES, UNIT_FILTER, DOC_YEAR_FILTER, REQUIRE_LISTING, ALLOW_CLIENTS, UPDATE_KEY_COL, UPDATE_COL, UPDATE_MAXLEN, ACTIVE, REMARKS, OPTIONS)
      VALUES (SEQ_MOBILE_MASTER_CONFIG.NEXTVAL, cid, 'MVC', d.SEQ_NO, d.ITEM_KEY, d.DESCRIPTION, d.OP_TYPE, d.SCHEMA_SOURCE, 'TMVC_' || d.TABLE_NAME, d.COLUMN_LIST, d.ALIASES,
             d.FILTER_COLUMN, d.FILTER_VALUES, d.UNIT_FILTER, d.DOC_YEAR_FILTER, d.REQUIRE_LISTING, d.ALLOW_CLIENTS, d.UPDATE_KEY_COL, d.UPDATE_COL, d.UPDATE_MAXLEN, 'Y', 'MVC TEST override', d.OPTIONS);
    END IF;
  END LOOP;
  COMMIT;
END;
