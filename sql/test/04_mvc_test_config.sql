-- MVC TEST CONFIG: turns the XYZADMIN test login into an MVC client (LOCA ATE, UNIT ANANDA, DOC_YEAR 2027) whose masters come from the
-- CLASSICNEW.TMVC_* copies, using per-client override rows (CTRL_ID set) in MOBILE_MASTER_CONFIG. XYZADMIN: password 1234.
ALTER SESSION SET CURRENT_SCHEMA = CLASSICNEW;

DECLARE
  cid NUMBER;
  n   NUMBER;
BEGIN
  SELECT CTRL_ID INTO cid FROM MOBILE_CONTROL WHERE UPPER(USER_ID) = 'XYZADMIN';
  UPDATE MOBILE_CONTROL
     SET LOCA = 'ATE', UNIT = 'ANANDA', DOC_YEAR = '2027', SCHEMA_NAME = 'CLASSICNEW', DATABASE_NAME = 'CLASSICDEV',
         IP_ADDRESS = '103.234.116.64', HOSTED_PORT = 90, CLIENT_NAME_DISPLAY = 'MVC TEST', STATUS = 'Y', PHONE_ID = NULL,
         MOBILE_ACTIVE_DATE = TRUNC(SYSDATE) - 1, MOBILE_VALIDITY = TRUNC(SYSDATE) + 30
   WHERE CTRL_ID = cid;

  FOR d IN (SELECT * FROM MOBILE_MASTER_CONFIG
             WHERE CTRL_ID IS NULL AND APP_MODE = 'MVC'
               AND ITEM_KEY IN ('unit','tea-estate','hazira-type','division','dek','sardar','employee','kamjari','section','leaf-type','moisture')) LOOP
    SELECT COUNT(*) INTO n FROM MOBILE_MASTER_CONFIG WHERE CTRL_ID = cid AND APP_MODE = 'MVC' AND ITEM_KEY = d.ITEM_KEY;
    IF n = 0 THEN
      INSERT INTO MOBILE_MASTER_CONFIG (CFG_ID, CTRL_ID, APP_MODE, SEQ_NO, ITEM_KEY, DESCRIPTION, OP_TYPE, SCHEMA_SOURCE, TABLE_NAME, COLUMN_LIST, ALIASES,
             FILTER_COLUMN, FILTER_VALUES, UNIT_FILTER, DOC_YEAR_FILTER, REQUIRE_LISTING, ALLOW_CLIENTS, UPDATE_KEY_COL, UPDATE_COL, UPDATE_MAXLEN, ACTIVE, REMARKS)
      VALUES (SEQ_MOBILE_MASTER_CONFIG.NEXTVAL, cid, 'MVC', d.SEQ_NO, d.ITEM_KEY, d.DESCRIPTION, d.OP_TYPE, 'CLIENT', 'TMVC_' || d.TABLE_NAME, d.COLUMN_LIST, d.ALIASES,
             d.FILTER_COLUMN, d.FILTER_VALUES, d.UNIT_FILTER, d.DOC_YEAR_FILTER, 'N', d.ALLOW_CLIENTS, d.UPDATE_KEY_COL, d.UPDATE_COL, d.UPDATE_MAXLEN, 'Y', 'MVC TEST override');
    END IF;
  END LOOP;
  COMMIT;
END;
/
