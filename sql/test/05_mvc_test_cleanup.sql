-- Removes everything 03 / 04 created and puts the XYZADMIN test login back to an inactive VB test row.
ALTER SESSION SET CURRENT_SCHEMA = CLASSICNEW;

DECLARE
  cid NUMBER;
BEGIN
  SELECT CTRL_ID INTO cid FROM MOBILE_CONTROL WHERE UPPER(USER_ID) = 'XYZADMIN';
  DELETE FROM MOBILE_MASTER_CONFIG WHERE CTRL_ID = cid AND REMARKS = 'MVC TEST override';
  UPDATE MOBILE_CONTROL
     SET LOCA = NULL, UNIT = NULL, DOC_YEAR = '2027', SCHEMA_NAME = 'PAY_BATE_NOR2027', DATABASE_NAME = 'CLASSICDEV',
         CLIENT_NAME_DISPLAY = NULL, STATUS = 'N', PHONE_ID = NULL, MOBILE_ACTIVE_DATE = NULL, MOBILE_VALIDITY = NULL
   WHERE CTRL_ID = cid;
  FOR t IN (SELECT table_name FROM user_tables WHERE table_name LIKE 'TMVC\_%' ESCAPE '\') LOOP
    EXECUTE IMMEDIATE 'DROP TABLE CLASSICNEW.' || t.table_name || ' PURGE';
  END LOOP;
  COMMIT;
END;
/
