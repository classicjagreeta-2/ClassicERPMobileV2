-- MVC TEST DATA (CLASSICDEV only). Copies the dev masters of PAY_BATE_NOR2027 into CLASSICNEW.TMVC_* and gives them UNIT / DOC_YEAR values
-- so the MVC filters (LOCA + UNIT, + DOC_YEAR where flagged) can be tested against real Oracle. Remove with 05_mvc_test_cleanup.sql.
ALTER SESSION SET CURRENT_SCHEMA = CLASSICNEW;

DECLARE
  n NUMBER;
BEGIN
  FOR t IN (SELECT column_value tn FROM TABLE(sys.odcivarchar2list('M_TEA_ESTATE','M_HAZIRATYPE','M_DVSN','M_DEK','M_SARDAR','M_EMPL','M_KAMJARI','M_SECT','M_ELPTYP','M_MOISTURE'))) LOOP
    SELECT COUNT(*) INTO n FROM user_tables WHERE table_name = 'TMVC_' || t.tn;
    IF n = 0 THEN
      EXECUTE IMMEDIATE 'CREATE TABLE CLASSICNEW.TMVC_' || t.tn || ' AS SELECT * FROM PAY_BATE_NOR2027.' || t.tn;
      EXECUTE IMMEDIATE 'ALTER TABLE CLASSICNEW.TMVC_' || t.tn || ' MODIFY (UNIT VARCHAR2(20))';
      -- the three estates become the three units of one company
      EXECUTE IMMEDIATE 'UPDATE CLASSICNEW.TMVC_' || t.tn || q'[ SET UNIT = CASE LOCA WHEN 'ATE' THEN 'ANANDA' WHEN 'BTE' THEN 'BORDEOBAM' WHEN 'PTE' THEN 'PATHALIPAM' ELSE LOCA END]';
    END IF;
  END LOOP;

  -- DOC_YEAR only where the MVC design has it (tea-estate, hazira-type): 2027 everywhere, 2026 for the BORDEOBAM rows (proves the filter)
  FOR t IN (SELECT column_value tn FROM TABLE(sys.odcivarchar2list('M_TEA_ESTATE','M_HAZIRATYPE'))) LOOP
    SELECT COUNT(*) INTO n FROM user_tab_columns WHERE table_name = 'TMVC_' || t.tn AND column_name = 'DOC_YEAR';
    IF n = 0 THEN
      EXECUTE IMMEDIATE 'ALTER TABLE CLASSICNEW.TMVC_' || t.tn || ' ADD (DOC_YEAR VARCHAR2(10))';
      EXECUTE IMMEDIATE 'UPDATE CLASSICNEW.TMVC_' || t.tn || q'[ SET DOC_YEAR = CASE UNIT WHEN 'BORDEOBAM' THEN '2026' ELSE '2027' END]';
    END IF;
  END LOOP;

  SELECT COUNT(*) INTO n FROM user_tables WHERE table_name = 'TMVC_M_MAST_UNIT';
  IF n = 0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE CLASSICNEW.TMVC_M_MAST_UNIT (ID NUMBER, LOCA VARCHAR2(10), UNIT VARCHAR2(20), CODE VARCHAR2(10), DESCRIPTION VARCHAR2(60), PTYPE VARCHAR2(2))';
    EXECUTE IMMEDIATE q'[INSERT INTO CLASSICNEW.TMVC_M_MAST_UNIT VALUES (1, 'ATE', 'ANANDA', 'ANAN', 'ANANDA TEA ESTATE', 'W')]';
    EXECUTE IMMEDIATE q'[INSERT INTO CLASSICNEW.TMVC_M_MAST_UNIT VALUES (2, 'BTE', 'BORDEOBAM', 'BORD', 'BORDEOBAM TEA ESTATE', 'W')]';
    EXECUTE IMMEDIATE q'[INSERT INTO CLASSICNEW.TMVC_M_MAST_UNIT VALUES (3, 'PTE', 'PATHALIPAM', 'PATH', 'PATHALIPAM TEA ESTATE', 'W')]';
  END IF;
  COMMIT;
END;
